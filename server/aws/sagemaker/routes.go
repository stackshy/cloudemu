// byName adapts a driver call that takes only a resource name into a handler.
func (h *Handler) byName(field string, fn func(driver.Service, context.Context, string) error) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		stopByName(w, r, field, func(ctx context.Context, name string) error { return fn(h.svc, ctx, name) })
	}
}
