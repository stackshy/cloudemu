func TestDeleteIdempotent(t *testing.T) {
	ctx := context.Background()
	m := newMock()
	createStd(t, m)

	existed, err := m.Delete(ctx, "sub", "rg", "graf1")
	if err != nil || !existed {
		t.Fatalf("first delete: err=%v existed=%v", err, existed)
	}

	existed, err = m.Delete(ctx, "sub", "rg", "graf1")
	if err != nil || existed {
		t.Fatalf("second delete: err=%v existed=%v, want existed=false", err, existed)
	}
}

func TestListAndPurge(t *testing.T) {
	ctx := context.Background()
	m := newMock()

	for _, n := range []string{"a", "b"} {
		if _, _, err := m.CreateOrUpdate(ctx, "sub", "rg", n, "eastus", &managedgrafana.Input{}); err != nil {
			t.Fatalf("create %s: %v", n, err)
		}
	}

	if _, _, err := m.CreateOrUpdate(ctx, "sub", "rg2", "c", "eastus", &managedgrafana.Input{}); err != nil {
		t.Fatalf("create c: %v", err)
	}

	byRG, _ := m.ListByResourceGroup(ctx, "sub", "rg")
	if len(byRG) != 2 {
		t.Errorf("ListByResourceGroup = %d, want 2", len(byRG))
	}

	bySub, _ := m.ListBySubscription(ctx, "sub")
	if len(bySub) != 3 {
		t.Errorf("ListBySubscription = %d, want 3", len(bySub))
	}

	if err := m.PurgeResourceGroup(ctx, "sub", "rg"); err != nil {
		t.Fatalf("purge: %v", err)
	}

	bySub, _ = m.ListBySubscription(ctx, "sub")
	if len(bySub) != 1 {
		t.Errorf("after purge ListBySubscription = %d, want 1", len(bySub))
	}
}

func TestSnapshotRestore(t *testing.T) {
	ctx := context.Background()
	m := newMock()
	created := createStd(t, m)

	data, err := m.Snapshot(ctx, false)
	if err != nil {
		t.Fatalf("snapshot: %v", err)
	}

	restored := newMock()
	if err := restored.Restore(ctx, data); err != nil {
		t.Fatalf("restore: %v", err)
	}

	got, err := restored.Get(ctx, "sub", "rg", "graf1")
	if err != nil {
		t.Fatalf("get after restore: %v", err)
	}

	if got.Endpoint != created.Endpoint || got.Identity.PrincipalID != created.Identity.PrincipalID {
		t.Errorf("restore lost stable fields: endpoint %q vs %q", got.Endpoint, created.Endpoint)
	}
}

